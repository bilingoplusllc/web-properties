"""Слой данных доски: окна СЧИТАЮТСЯ из посуточного ряда, а не набираются руками.

Почему так, а не как было. Раньше в генераторе лежал словарь с двумя готовыми
срезами, набранными с экрана вручную. У этого три беды сразу:

  1. Набранное руками число проходит мимо всех гейтов — они читают собранный
     HTML, а не источник. Один и тот же класс ошибки уже стоил нам пяти макетов
     с чужими цифрами.
  2. Два готовых среза нельзя пересечь, сдвинуть или сравнить между собой.
     Вопрос «а что было на прошлой неделе» не имел ответа в принципе.
  3. Среднее за всё время у молодого сайта — это среднее по ПАДАЮЩЕМУ тренду.
     У MileageCurve позиция 25,8 лежит ровно между 20,4 первой половины жизни
     и 40,1 второй. Сайт не был на 25,8 ни одного дня.

Теперь есть посуточный ряд, а любое окно — функция от него. Числа сходятся
с итогами Search Console до второго знака, и это проверяется гейтом.

ЧТО ТАКОЕ ПРАВЫЙ КРАЙ. Search Console отдаёт данные с задержкой два-три дня.
Правый край поисковых окон — НИКОГДА не сегодня, а последний день, который в
ряду есть. Иначе последние дни всегда выглядят провалом, которого нет.
"""
import csv
import io
import os
from datetime import date, timedelta

DIR = os.path.join(os.path.dirname(os.path.abspath(__file__)), "data")

def _head(name):
    """Строки-комментарии файла. В них живут дата съёмки и сверка."""
    with io.open(os.path.join(DIR, name), encoding="utf-8") as f:
        return [l for l in f if l.startswith("#")]


def _ga_window():
    """Окно поведенческих чисел GA4 — ИЗ ШАПКИ ФАЙЛА.

    В генераторе оно стояло литералом «GA4, 3–30 августа» и печаталось под
    всеми тремя панелями сразу. Литерал не привязан ни к чему, что меняет
    бот: файл давно снят за другое окно, а подпись под ним осталась
    августовской и не исправится ни в один день.

    Второе, что этот разбор делает явным: окно у GA4 ОДНО. Панели «7 дней»,
    «28 дней» и «с запуска» переключают только поисковые числа; под ними
    стоят одни и те же поведенческие. Раз так, подпись обязана называть
    настоящее окно, а не наследовать заголовок панели.
    """
    import re
    for line in _head("ga4_channels.csv"):
        m = re.search(r"(\d{4}-\d{2}-\d{2})\.\.(\d{4}-\d{2}-\d{2})", line)
        if m:
            a, b = _d(m.group(1)), _d(m.group(2))
            return "GA4, %s–%s" % (a.strftime("%d.%m"), b.strftime("%d.%m.%Y"))
        m = re.search(r"окно ([^.,;]+)", line)     # эпоха ручного снятия
        if m:
            return "GA4, " + m.group(1).strip()
    raise RuntimeError(
        "в шапке ga4_channels.csv нет окна. Подписать поведенческие числа "
        "нечем, а подпись из генератора уже один раз пережила свои данные.")


def _index_census():
    """Перепись индексации по адресам. ОТСУТСТВИЕ — это «не снято», а не ноль.

    Три величины выводятся из ДОКУМЕНТИРОВАННЫХ полей ответа Google, а не из
    перевода строки-причины:

      в индексе          verdict == PASS
      обошёл и не взял   verdict != PASS, при этом lastCrawlTime ЕСТЬ
      нашёл и не обошёл  verdict != PASS, lastCrawlTime отсутствует

    Разница между двумя последними — это разница между приговором содержанию
    и очередью обхода, и чинятся они противоположным. Строку `coverage` мы
    храним и показываем, но НЕ считаем по ней: у неё нет объявленного набора
    значений, и Google переводит её по параметру языка.

    Адрес без даты проверки в счёт не идёт вовсе: «не смотрели» — это третье
    состояние, и подменять его нулём значит объявить страницу невзятой.
    """
    path = os.path.join(DIR, "index_state.csv")
    if not os.path.exists(path):
        return None
    rows = _rows("index_state.csv")
    if not rows:
        return None
    out = {}
    for r in rows:
        a = out.setdefault(r["site"], {
            "total": 0, "seen": 0, "indexed": 0, "crawled_not": 0,
            "queued": 0, "dates": [], "reasons": {}})
        a["total"] += 1
        if not r.get("checked"):
            continue
        a["seen"] += 1
        a["dates"].append(r["checked"])
        if r.get("verdict") == "PASS":
            a["indexed"] += 1
            continue
        why = r.get("coverage") or "причина не названа"
        a["reasons"][why] = a["reasons"].get(why, 0) + 1
        if r.get("last_crawl"):
            a["crawled_not"] += 1
        else:
            a["queued"] += 1
    for k, a in out.items():
        if a["indexed"] + a["crawled_not"] + a["queued"] != a["seen"]:
            raise RuntimeError(
                "%s: перепись не сходится — %d + %d + %d против %d опрошенных"
                % (k, a["indexed"], a["crawled_not"], a["queued"], a["seen"]))
        a["from"] = _d(min(a["dates"])) if a["dates"] else None
        a["to"] = _d(max(a["dates"])) if a["dates"] else None
        a["reasons"] = sorted(a["reasons"].items(), key=lambda x: (-x[1], x[0]))
        del a["dates"]
    return out


def _sc_check():
    """Эталон СО СТОРОНЫ: итог окна, посчитанный самим Search Console.

    Сумму ряда считаем мы; этот итог приходит отдельным запросом БЕЗ разбивки
    по дням, то есть его считает не наш код. Сверять сумму ряда с самой собой
    бессмысленно — на этом уже обжигались.

    Пока ряд снимали руками, эталоном были числа с экрана, вбитые в
    генератор. Их дата заморожена навсегда, поэтому с приходом бота они
    перестают годиться: не совпадут не потому, что ряд неверен, а потому что
    он новее эталона. Возвращаем None, когда строки сверки в файле нет, —
    вызывающий обязан назвать, какой эталон он взял.
    """
    import re
    for line in _head("daily_search.csv"):
        if "СВЕРКА" not in line:
            continue
        m = re.search(r"окно (\d{4}-\d{2}-\d{2})\.\.(\d{4}-\d{2}-\d{2})", line)
        pairs = re.findall(r"([a-z0-9_]+)=(\d+)/(\d+)/([\d.]+)", line)
        if not m or not pairs:
            raise RuntimeError(
                "строка СВЕРКИ есть, но не разбирается: %r. Молча пропустить "
                "её значит остаться без эталона и не заметить этого." % line)
        return {"from": _d(m.group(1)), "to": _d(m.group(2)),
                "sites": {k: (int(c), int(i), float(p)) for k, c, i, p in pairs}}
    return None


def _captured():
    """Дата снятия — ИЗ ФАЙЛА, а не литералом.

    Все окна отсчитываются от края РЯДА, а не отсюда; это поле нужно, чтобы
    честно подписать возраст данных и посчитать отставание края от съёмки.
    Пока ряд снимали руками, литерал был правдой. С того дня, как его начал
    переписывать бот, литерал стал бы враньём, которое никто не заметит:
    числа свежие, подпись — августовская. Поэтому дата берётся из шапки того
    самого файла, откуда взяты числа, и её отсутствие — отказ, а не повод
    подставить сегодня.
    """
    import re
    for line in _head("daily_search.csv"):
        # Дата берётся ТОЛЬКО из строки со словом «Снято». В шапке есть и
        # другие даты — границы окна, — и первая попавшаяся дала бы левый
        # край окна вместо дня съёмки.
        if "нято" not in line:
            continue
        m = re.search(r"(\d{4})-(\d{2})-(\d{2})", line)      # снято ботом
        if m:
            return date(*map(int, m.groups()))
        m = re.search(r"(\d{2})\.(\d{2})\.(\d{4})", line)    # снято руками
        if m:
            d, mo, y = map(int, m.groups())
            return date(y, mo, d)
    raise RuntimeError(
        "в шапке daily_search.csv нет даты снятия. Подписать возраст данных "
        "нечем, а подставить сегодня значит объявить свежим что угодно.")


CAPTURED = _captured()


def _rows(name):
    """CSV без строк-комментариев. Комментарии здесь несут больше, чем данные."""
    with io.open(os.path.join(DIR, name), encoding="utf-8") as f:
        return list(csv.DictReader(l for l in f if not l.startswith("#")))


def _d(s):
    return date(*map(int, s.split("-")))


