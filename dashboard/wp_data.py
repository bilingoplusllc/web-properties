# Дата запуска сайта. Живёт ЗДЕСЬ, а не в генераторе, потому что от неё
# зависит сам ряд: Search Console отдаёт сутки ДО первого показа нулями (у
# gspaytables это 24 и 25 августа при запуске 26-го), и эти сутки попадали в
# «было» у сравнения окон. Они занижали знаменатель и рисовали рост, которого
# не было: «показов в сутки 517 → 1035, +100%» на выложенной странице.
# Обрезаем ОДИН раз при загрузке — иначе каждый потребитель обязан помнить
# про запуск, а `window_pair` про него уже забыл, хотя и принимал аргументом.
LAUNCH = {
    "mileagecurve": date(2026, 8, 12),
    "gspaytables": date(2026, 8, 26),
}


def _load_search():
    out = {}
    unknown = set()
    for r in _rows("daily_search.csv"):
        site = r["site"]
        if site not in LAUNCH:
            unknown.add(site)
            continue
        if _d(r["day"]) < LAUNCH[site]:
            continue                    # сайта ещё не было — это не его сутки
        out.setdefault(site, []).append(
            (_d(r["day"]), int(r["clicks"]), int(r["impressions"]),
             float(r["position"])))
    if unknown:
        # Тихо выбросить сайт значит показать доску без него и не заметить.
        raise RuntimeError(
            "в ряду есть сайты без даты запуска: %s. Допиши их в LAUNCH — "
            "без даты запуска нельзя ни обрезать ряд, ни считать «в день»."
            % ", ".join(sorted(unknown)))
    for k in out:
        out[k].sort()
    for k, v in out.items():
        # ЛЕВЫЙ КРАЙ обязан доставать до запуска. Загрузчик тянет окно в 90
        # суток; пока он это окно ДОПИСЫВАЕТ, ряд полон. Если он снова начнёт
        # им ЗАМЕНЯТЬ файл, ряд обрежется слева, «с запуска» станет считаться
        # по обрубку и начнёт уменьшаться само по себе — беззвучно, потому что
        # почти каждая проверка сверяет окно с итогом за то же окно.
        # Ловим ЗДЕСЬ, а не гейтом: на обрубке генератор падает раньше, чем
        # доходит до гейтов, и падение выглядит случайной поломкой кода.
        if (v[0][0] - LAUNCH[k]).days > 3:
            raise RuntimeError(
                "%s: ряд начинается %s, а сайт запущен %s. Либо файл обрезали "
                "слева — загрузчик обязан ДОПИСЫВАТЬ окно, а не заменять им "
                "ряд, — либо у сайта первые сутки прошли без единого показа; "
                "тогда подвинь дату в LAUNCH и напиши почему."
                % (k, v[0][0], LAUNCH[k]))
    return out


DAILY = _load_search()

