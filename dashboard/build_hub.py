def chapter(c):
    body = "".join(f"<p>{p}</p>" for p in c["body"])
    return f"""
  <section class="ch" id="{c['id']}">
    <div class="ch-h"><span class="ch-n">{c['n']}</span>
      <h2>{c['t']}</h2></div>
    <p class="ch-lead">{c['lead']}</p>
    <div class="ch-b">{body}</div>
    <p class="ch-src">Источник: {c['src']}</p>
  </section>"""


