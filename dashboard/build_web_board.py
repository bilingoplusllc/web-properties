def aside_row(name, why, value, scale, ref, ref_label, shown, tone):
    """Отметка как метрика: имя, обоснование, штрихованная дорожка с меткой
    эталона и число. Штриховка и метка — то, чем отметка отличается от
    слагаемого: у слагаемого эталон и есть сто баллов, отдельной метки ему
    не нужно."""
    w = round(max(2, min(100, value / scale * 100)), 1)
    rp = round(ref / scale * 100, 1)
    return (f'<div class="ip aside"><span class="ip-n">{name}</span>'
            f'<span class="ip-w">{why}</span>'
            f'<span class="ip-bar dash"><i class="{tone}" style="width:{w}%"></i>'
            f'<u style="left:{rp}%" title="{ref_label}"></u></span>'
            f'<b class="ip-v">{shown}</b></div>')


def idx_row(name, what, rule, why, v, gap_note):
    """Одна строка признака. Неизмеренный отличается от нулевого и видом,
    и подписью: пустая полоса читается как «очень плохо», а это не то."""
    if v is None:
        return (f'<div class="ip none">'
                f'<span class="ip-n">{tip(name, what + ". " + rule)}</span>'
                f'<span class="ip-w">{gap_note}</span>'
                f'<span class="ip-bar dash"></span>'
                f'<b class="ip-v">н/д</b></div>')
    return (f'<div class="ip"><span class="ip-n">{tip(name, what + ". " + rule)}</span>'
            f'<span class="ip-w">{why}</span>'
            f'<span class="ip-bar"><i class="{idx_tone(v)}" style="width:{v}%"></i></span>'
            f'<b class="ip-v">{v}</b></div>')


