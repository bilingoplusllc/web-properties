# 14. Ссылка в документацию должна вести в СУЩЕСТВУЮЩУЮ главу. Доска и хаб —
#     два разных генератора, и якорь в одном молча переживает переименование
#     главы в другом: ссылка останется, а откроется просто начало страницы.
_hubp = os.path.join(os.path.dirname(os.path.abspath(__file__)), "hub.html")
if os.path.exists(_hubp):
    _hub = io.open(_hubp, encoding="utf-8").read()
    #     chr(34) — двойная кавычка. Собирается из кода, а не пишется в
    #     литерале, потому что при переносе правки через оболочку кавычки и
    #     обратные слэши теряют смысл. Предыдущая попытка обернула шаблон
    #     апострофами через chr(39), и он стал требовать апостроф В ТЕКСТЕ:
    #     гейт печатал «пройдено», не совпадая ни с чем.
    _q = chr(34)
