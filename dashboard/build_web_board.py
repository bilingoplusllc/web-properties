#     общих признаках было бы 52 против 73. Число, посчитанное по разному
#     набору слагаемых, нельзя ставить рядом молча.
_counts = {s["key"]: idx_measured(s["key"], s, DEFAULT_PERIOD) for s in SITES}
_g.append(_gate("индекс считается по одинаковому набору признаков",
                len(set(_counts.values())) == 1, str(_counts)))

#     18д. Переходы ВНУТРИ индекса, а не рядом с ним. Признак «люди приходят»
#     обязан присутствовать: без него индекс однажды снова начнёт расти на
#     сайте, который не получил ни одного перехода.
_g.append(_gate("переходы входят в индекс",
                any("Люди приходят" == n for n, _w, _r in IDX_PARTS),
                str([n for n, _w, _r in IDX_PARTS])))

# 17. ПЕРЕПИСЬ ИНДЕКСАЦИИ. Это были единственные числа на доске, которые не
#     приходили ниоткуда: рукописный словарь с датами 21.08 и 26.08 на
#     странице, где плашка объявляла ВСЕ числа снятыми сегодня. Ни один из
#     56 гейтов их не читал.
for _s in SITES:
    _k = _s["key"]
    _c = census(_k)
    #     Проверяем В САМОМ БЛОКЕ, а не по всей странице: дата съёмки стоит и в
    #     плашке шапки, и слово «перепись» встречается в таблице сравнения —
    #     любая из этих строк удовлетворила бы проверку по всему HTML, пока сам
    #     блок молчит. Гейт, которому хватает соседа, ничего не охраняет.
    _ib = index_block(_k, _s, "life")
    if _c is None:
        #     Не снято — это состояние, и оно обязано быть НАЗВАНО на месте.
        #     Молчаливое исчезновение блока читается как «всё в порядке».
        _g.append(_gate("отсутствие переписи названо в самом блоке: " + _k,
                        "не снята" in _ib,
                        "переписи нет, а блок об этом молчит"))
        continue
    #     Части обязаны складываться в целое. Пока «в индексе» приходило из
    #     API, а «в очереди» оставалось рукописным, страница могла напечатать
    #     часть больше целого.
    _g.append(_gate("перепись сходится: " + _k,
                    _c["indexed"] + _c["crawled_not"] + _c["queued"] == _c["seen"]
                    and _c["seen"] <= _c["total"],
                    "%d+%d+%d против %d опрошенных из %d"
                    % (_c["indexed"], _c["crawled_not"], _c["queued"],
                       _c["seen"], _c["total"])))
    #     Знаменатель доли — КАРТА САЙТА, и она же печатается как «страниц
    #     собрано». Прежний гейт сверял карту с литералом в SITES и уронил
    #     сборку в тот день, когда сайт честно уменьшился с 353 до 307:
    #     свежие данные NHTSA вывели часть поколений за порог отчётов. Литерал
    #     был неправ, а не карта — и гейт, который каждый месяц роняет доску на
    #     законном изменении, снимут первым. Теперь литерала в счёте нет вовсе,
    #     а проверяется то, что стоит на странице.
    _g.append(_gate("страниц на доске столько же, сколько в карте сайта: " + _k,
                    str(_c["total"]) in _ib and pages_of(_k, _s) == _c["total"],
                    "в карте %d, напечатано иначе" % _c["total"]))
    #     Гейта «доля не больше ста» здесь НЕТ намеренно. В прежней сборке
    #     риск был настоящий: «в индексе» приходило бы из API, а знаменатель
    #     стоял рукописным, и лишний адрес давал бы полосу width:101%. Теперь
    #     числитель и знаменатель — одна и та же перепись, доля больше ста
    #     невозможна по построению, и такая проверка не смогла бы покраснеть
    #     никогда. Знаменатель охраняет гейт выше: карта против SITES.
    #     Дата переписи печатается ИЗ ПЕРЕПИСИ. У неё своя дата, отдельная от
    #     wp.CAPTURED: третий файл данных мог бы протухнуть незаметно.
    _g.append(_gate("дата переписи напечатана в самом блоке: " + _k,
                    d(_c["to"]) in _ib,
                    "в файле край %s, а блок его не печатает" % d(_c["to"])))
    #     И ПЕРЕСЧЁТ ИЗ СЫРЫХ СТРОК, независимый от разбора в слое данных.
    #     Без него подмена признака проходит молча: если «обошёл и не взял»
    #     начнёт считаться как «нашёл и не обошёл», сумма частей сойдётся
    #     по-прежнему, а диагноз на странице поменяется на противоположный —
    #     между «содержание не убедило» и «до страницы не дошли» вся разница.
    _raw = [r for r in wp._rows("index_state.csv") if r["site"] == _k]
    _rc = {
        "total": len(_raw),
        "seen": sum(1 for r in _raw if r["checked"]),
        "indexed": sum(1 for r in _raw if r["checked"] and r["verdict"] == "PASS"),
        "crawled_not": sum(1 for r in _raw if r["checked"] and r["verdict"] != "PASS"
                           and r["last_crawl"]),
        "queued": sum(1 for r in _raw if r["checked"] and r["verdict"] != "PASS"
                      and not r["last_crawl"]),
    }
    _bad = {n: (_rc[n], _c[n]) for n in _rc if _rc[n] != _c[n]}
    _g.append(_gate("пересчёт переписи из сырых строк сходится: " + _k,
                    not _bad, str(_bad)))

# 16. Окно поведенческих чисел на странице — то же, что в шапке их файла.
#     Литерал «GA4, 3–30 августа» пережил свои данные: файл давно снят за
#     другое окно, а подпись под ним осталась августовской.
_g.append(_gate("окно GA4 на странице совпадает с окном файла",
                wp.GA_WINDOW in HTML,
                "в файле «%s», а на странице его нет" % wp.GA_WINDOW))

io.open(OUT, "w", encoding="utf-8", newline="\n").write(HTML)
print("web board written:", len(HTML), "chars ->", OUT)
print("гейтов пройдено:", len(_g))
