def ru_time(x):
    """GA4 отдаёт «1m 43s» и «14s». На русской доске это читается как
    недопереведённый интерфейс, а не как величина."""
    m = re.match(r"(?:([0-9]+)m )?([0-9]+)s", x.strip())
    if not m:
        return x
    mins, secs = m.group(1), int(m.group(2))
    if mins:
        return "%s мин %02d с" % (mins, secs)
    return "%d сек" % secs


def compare_rows():
    def val(x):
        m = re.findall(r"\d+(?:[.,]\d+)?", x.replace(" ", ""))
        return float(m[0].replace(",", ".")) if m else None

    out = []
    for label, fn, better in COMPARE:
        cells = [fn(s["key"], s) for s in SITES]
        best = -1
        if better:
            nums = [val(c) for c in cells]
            if all(n is not None for n in nums) and nums[0] != nums[1]:
                best = nums.index(min(nums) if better == "min" else max(nums))
        tds = "".join(f'<td class="num{" win" if i == best else ""}">{c}</td>'
                      for i, c in enumerate(cells))
        out.append(f"<tr><th>{label}</th>{tds}</tr>")
    return "".join(out)



def _esc(s):
    """В разметку кладётся экранированное. Своя, потому что в этом генераторе
    общей нет: остальной текст — литералы шаблона."""
    return (str(s).replace("&", "&amp;").replace("<", "&lt;")
            .replace(">", "&gt;").replace('"', "&quot;"))


def pipeline_block():
    """Три сайта, которые ещё строятся. Читает снимок data/pipeline.json."""
    p = os.path.join(_HERE, "data", "pipeline.json")
    if not os.path.exists(p):
        return ""
    snap = json.loads(io.open(p, encoding="utf-8").read())
    rows = []
    for s in snap.get("sites", []):
        if s.get("missing"):
            rows.append(
                '<div class="warn"><b>%s</b> — каталога нет на машине, где '
                'снимался снимок. Это не ноль страниц, это «не смотрели».'
                '</div>' % _esc(s["name"]))
            continue
        blockers = "".join("<li>%s</li>" % _esc(b) for b in s["blockers"])
        rows.append(
            '<details class="cmp"><summary>'
            '<span class="s-name">%s</span>'
            '<span class="s-sum">%s страниц · %s гейтов · домен с %s</span>'
            '</summary><div class="s-body">'
            '<p>%s</p>'
            '<p><b>Облик:</b> %s</p>'
            '<p><b>Что мешает запуску:</b></p><ul>%s</ul>'
            '</div></details>'
            % (_esc(s["name"]), s["pages"], s["gates"], _esc(s["domain"]),
               _esc(s["niche"]), _esc(s["design"]), blockers))
    return (
        '<section><h2>В сборке</h2>'
        '<div class="warn" style="margin:0 0 14px">'
        '<b>У этих сайтов нет показателей, и это не пропуск в данных.</b> '
        'Ни один не опубликован: ни домена в работе, ни Search Console, ни '
        'единого визита. Мерить нечего, поэтому здесь стоит СТАДИЯ. '
        'Страницы и гейты посчитаны из репозиториев, снимок снят '
        '<b>%s</b>; остальное объявлено с причиной.'
        '</div>%s</section>' % (_esc(snap.get("taken", "?")), "".join(rows)))


