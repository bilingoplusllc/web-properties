# Узлы кривой видимости. Кликабельность падает не по прямой: между первым и
# третьим местом разница огромная, между двадцать пятым и тридцатым — никакой.
VIS_POINTS = [(1, 100), (3, 80), (10, 50), (20, 20), (30, 0)]


def vis_score(pos):
    """Плато 1–3 убрано НАРОЧНО: пока третье место равнялось первому,
    видимость переставала расти у вершины, и вклад позиции там держала одна
    только отдача — со знаком минус. Отсюда и брался провал индекса при
    выходе в топ. Пол опущен до нуля: комментарий обещал «30-е и ниже = ноль»,
    а функция возвращала пять — код противоречил сам себе в соседних строках."""
    if pos <= 1:
        return 100.0
    if pos >= 30:
        return 0.0
    for (x1, y1), (x2, y2) in zip(VIS_POINTS, VIS_POINTS[1:]):
        if x1 <= pos <= x2:
            return y1 + (pos - x1) / (x2 - x1) * (y2 - y1)
    return 5.0


def expected_ctr(pos):
    """Сколько переходов обычно даёт ЭТА позиция. Отраслевая кривая
    0.28 * позиция^-0.7; нужна, чтобы отделить «нас не выбирают» от
    «мы просто стоим низко». Без неё CTR был бы дублем позиции."""
    return 0.28 * pos ** -0.7 * 100


# Ниже этого числа визитов доля не считается. Интервал на 50% при шести
# наблюдениях — примерно от 12% до 88%: по такому «признаку» нельзя не то что
# ставить балл, а даже сказать, в какую он сторону.
MIN_SESSIONS = 30


def idx_raw(k, s, per):
    """Сырые величины. Усредняются ОНИ, а округление одно и в самом конце:
    округлять части, а потом их среднее — значит заряжать люфт до половины
    балла на каждой.

    None означает НЕ ИЗМЕРЕНО, и это не ноль: ноль — это «плохо», а None —
    «нечем судить». Разница видна на MileageCurve, где три вовлечённых визита
    из шести давали ровно планку и ровно сто баллов.
    """
    m = mm(k, per)
    eng = float(m["engagement"].replace("%", "").replace(",", "."))
    beh = (min(100.0, eng / 50 * 100)
           if m["sessions"] >= MIN_SESSIONS else None)
    return [
        m["indexed"] / s["pages"] * 100,
        vis_score(float(m["position"])),
        beh,
    ]


def idx_parts(k, s, per):
    return [None if v is None else round(v) for v in idx_raw(k, s, per)]


def idx_measured(k, s, per):
    """Сколько признаков из трёх реально измерено."""
    return sum(1 for v in idx_raw(k, s, per) if v is not None)


def payoff(k, per):
    """Отдача — ОТМЕТКА, не слагаемое. Без обрезки: перевыполнение здесь
    как раз и есть то, что надо увидеть."""
    m = mm(k, per)
    pos = float(m["position"])
    ctr = float(m["ctr"].replace("%", "").replace(",", "."))
    exp = expected_ctr(pos)
    r = ctr / exp
    if r >= 1:
        word = f"в {num_ru(r)} раза лучше своего места"  # 1,2 / 1,5 — всегда «раза»
        tone = "good"
    else:
        k_ = round(1 / r)
        word = ("в " + plural(k_, "раз", "раза", "раз")
                + " хуже своего места")
        tone = "bad"
    # На виду — вывод. Всё «почему» уходит под наведение: под индексом
    # успела вырасти стена, где объяснение было длиннее самих данных.
    why = (f'Наш CTR {m["ctr"]} против {num_ru(exp)}%, которые обычно даёт '
           f'позиция {num_ru(pos)}. В среднее НЕ входит: это диагностика, а '
           f'не качество — чем ниже место, тем меньше от него ждут, и '
           f'величина улучшается, когда сайту хуже. Стоя в одном среднем с '
           f'самой позицией, она делала индекс немонотонным: выход на первое '
           f'место ронял его на девять баллов. Кривая ожидаемого — '
           f'приближение по публичным сводкам, мы её не перепроверяли; на '
           f'баллы не влияет.')
    return tone, word, why, r * 100


def num_ru(x, digits=1):
    return ("%.*f" % (digits, x)).replace(".", ",")


def idx_why(k, s, per):
    """Откуда взялся каждый балл. Обоснование обязано ДОВОДИТЬ до балла:
    владелец справедливо спросил, почему «7% при ожидаемых 5,8%» это сто —
    ответ (121% и обрезка) был в формуле, но не на экране."""
    m = mm(k, per)
    pos = float(m["position"])
    ctr = float(m["ctr"].replace("%", "").replace(",", "."))
    exp = expected_ctr(pos)
    ratio = ctr / exp * 100
    part = m["indexed"] / s["pages"] * 100
    eng = float(m["engagement"].replace("%", "").replace(",", "."))
    beh = (f'{m["engaged"]} из {m["sessions"]} визитов · {m["engagement"]}'
           f' · планка 50%')
    del exp, ratio, ctr
    lo = hi = None
    for (x1, y1), (x2, y2) in zip(VIS_POINTS, VIS_POINTS[1:]):
        if x1 <= pos <= x2:
            lo, hi = (x1, y1), (x2, y2)
            break
    if lo:
        vis_t = (f'позиция {num_ru(pos)} · между {lo[0]}-м ({lo[1]}) '
                 f'и {hi[0]}-м ({hi[1]})')
    else:
        vis_t = f'позиция {num_ru(pos)} · ниже 30-го места'
    idx_t = f'{m["indexed"]} из {s["pages"]} · {num_ru(part, 0)}%'
    if m["discovered"]:
        idx_t += f' · {m["discovered"]} в очереди на обход'
    return [idx_t, vis_t, beh]


def idx_score(k, s, per):
    """Среднее по ИЗМЕРЕННЫМ признакам. Неизмеренный не входит ни как ноль,
    ни как сто — он не входит никак, а его отсутствие подписано рядом."""
    r = [v for v in idx_raw(k, s, per) if v is not None]
    return round(sum(r) / len(r)) if r else 0


