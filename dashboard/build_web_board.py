# никогда, каким бы ни было отношение.
_bad = [(a, b) for a in range(0, 20) for b in range(0, 20)
        if a + b < 20 and wp.test_clicks(a, b)[0] != "не измерено"]
_g.append(_gate("при сумме меньше 20 разница не измеряется", not _bad,
                str(_bad[:5])))

# 4ж. Одинаковые id — невалидная разметка, и ссылка url(#…) в ней однажды
#      укажет не на тот узор. Лента рисуется трижды, по разу на окно.
_ids_all = re.findall('id=' + chr(34) + '([^' + chr(34) + ']+)' + chr(34), HTML)
_dups = sorted({i for i in _ids_all if _ids_all.count(i) > 1})
_g.append(_gate("нет повторяющихся id", not _dups, str(_dups)))

# 4з. Адрес, за которым браузер УЙДЁТ. Знак вставлялся как src="PHN2Zy…" —
#      голый base64 без схемы data:, и браузер принимал его за относительный
#      путь: пятнадцать 404 в консоли и битая картинка. Гейт «нет внешних
#      адресов» этого не видел, потому что искал http:// и https://, а тут не
#      было вообще никакой схемы. Проверять надо не запрещённое, а ВСЁ, за чем
#      браузер пойдёт.
_ATTR = re.findall('(?:src|href)=' + chr(34) + '([^' + chr(34) + ']*)' + chr(34),
                   HTML)
_bad_src = []
for _a in _ATTR:
    if not _a or _a.startswith("#"):
        continue
    if _a.startswith("data:"):
        # Схема есть — проверяем, что она полная, а не обрывок.
        if ";base64," not in _a and "," not in _a:
            _bad_src.append(_a[:40])
        continue
    # Якорь отсекается ДО проверки: «hub.html#sroki» — свой файл, а не
    # чужой адрес, и первая версия гейта покраснела на шести живых ссылках.
    _path = _a.split("#")[0]
    if _path.endswith(".html") or _path.endswith(".css"):
        continue
    _bad_src.append(_a[:40])
_g.append(_gate("нет адресов, за которыми браузер уйдёт наружу",
                not _bad_src, str(_bad_src)))

# 5. Съеденный эскейп печатается в текст голым шестнадцатеричным огрызком.
#    Иконка ссылки была записана как ЭСКЕЙП ПИТОНА "\1F4D8", питон съел \1 в
#    управляющий символ, CSS получил "F4D8" и напечатал его. Все десять гейтов
#    при этом были зелёные: они читали РАЗМЕТКУ, а не то, что видит человек.
_vis = _strip_code(HTML, " ")
#    Огрызок эскейпа — это НЕ просто набор из [0-9A-F]: под такой шаблон
#    подходит любой год («2026») и любое число показов («2466»), и первая
#    версия гейта покраснела на семидесяти семи законных числах. Признак
#    огрызка — буква A–F И цифра одновременно: «F4D8» подходит, «2026» нет
#    (нет буквы), «CAFE» нет (нет цифры).
_hex = [w for w in re.findall(r"\b[0-9A-F]{4,6}\b", _vis)
        if any(c.isdigit() for c in w) and any(c in "ABCDEF" for c in w)]
_g.append(_gate("нет съеденных эскейпов в видимом тексте", not _hex, str(_hex)))

# 6. Управляющих символов в собранном файле быть не должно вовсе.
_ctl = sorted({hex(ord(c)) for c in HTML if ord(c) < 9 or 13 < ord(c) < 32})
_g.append(_gate("нет управляющих символов", not _ctl, str(_ctl)))

# 7. Подсказка без текста — это подчёркнутое слово, которое ничего не
#    объясняет: рычаг есть, а за ним пусто. tip() молча отдаёт "" для слова,
#    которого нет в TIPS, и заметить это можно только в собранном файле.
_notip = re.findall(r'class="tip"[^>]*data-tip=""[^>]*>([^<]*)<', HTML)
_g.append(_gate("нет пустых подсказок", not _notip, str(sorted(set(_notip)))))

# 8. Испорченная десятичная запятая. «81 9%» вместо «81,9%» — след массовой
#    замены, которая не знала, где число, а где предложение. У нас это уже
#    было дважды: один раз замена переписала каждое «14» в CSS в тире, другой
#    съела запятые в процентах. Класс ошибки один: литерал не видит синтаксис.
#
#    Теги заменяются на ПЕРЕВОД СТРОКИ, а не на пробел: иначе соседние ячейки
#    таблицы слипаются, и «8» из одного столбца с «0%» из другого читаются
#    как испорченное число. Первая версия гейта покраснела на пятнадцати
#    законных строках именно так.
_seg = _strip_code(HTML, chr(10))
_broken = [m for line in _seg.split(chr(10))
           for m in re.findall(r"[0-9]+ [0-9]\s*(?:%|раза|раз)", line)]
_g.append(_gate("нет испорченных десятичных", not _broken, str(_broken)))

# 9. Непереведённая величина из чужого интерфейса. GA4 отдаёт «1m 43s», и
#    на русской доске это читается как недоделка, а не как время. Гейт
#    ловит алфавит источника в видимом тексте — тот же приём, которым мы
#    однажды поймали русский текст на английском сайте, только наоборот.
# Разбор ПО СЛОВАМ, без единого обратного слэша. Предыдущая версия этого
# гейта содержала в шаблоне байт 0x08 вместо двух символов, требовала от
# текста backspace и не совпадала никогда: проверяющий печатал «пройдено»,
# ничего не проверяя. Заодно шаблон ловил «2002 s» из запроса про Subaru.
_BAD_TAIL = ("m", "s")
_en = [w for line in _seg.split(chr(10)) for w in line.split()
       if len(w) > 1 and w[-1] in _BAD_TAIL and w[:-1].isdigit()]
_g.append(_gate("нет английских длительностей", not _en,
                str(sorted(set(_en)))))

# 10. Управляющий символ в ИСХОДНИКЕ. За один сеанс эскейп трижды
#     превратился в байт: 0x01 вместо иконки, неразрывный пробел вместо
#     обычного и 0x08 внутри шаблона этого самого гейта. Последнее опаснее
#     всех: ломается проверяющий, и доска молча перестаёт проверяться.
_srcbad = {}
for _f in (__file__, wp.__file__):
    _txt = io.open(_f, encoding='utf-8').read()
    _bad = sorted({hex(ord(c)) for c in _txt
                   if ord(c) < 9 or 13 < ord(c) < 32 or ord(c) == 0xA0})
    if _bad:
        _srcbad[os.path.basename(_f)] = _bad
_g.append(_gate("нет управляющих символов в исходниках", not _srcbad,
                str(_srcbad)))

# 11. Подпись под индексом против числа измеренных признаков. Две фразы об
#     одном факте обязаны сверяться ДРУГ С ДРУГОМ, а не каждая с кодом:
#     «Среднее трёх величин» полсуток стояло прямо под строкой «н/д».
