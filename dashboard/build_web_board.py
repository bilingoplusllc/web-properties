def tip(word, text=None):
    """Всплывающая подсказка. Термин без расшифровки на этой доске не живёт."""
    t = text or TIPS.get(word, "")
    return f'<span class="tip" tabindex="0" data-tip="{t}">{word}</span>'


def stat(big, label, hint, tone="", foot=""):
    """Квадрат с одной крупной величиной.

    hint — ПОЯСНЕНИЕ, и оно уходит под наведение на подпись, а не занимает
    строку под ней. Четыре квадрата в ряд давали четыре строки пояснений и
    съедали то место, ради которого квадрат и сделан: крупное число, видное
    сразу.

    foot остаётся видимым: это не пояснение, а оговорка о годности числа
    («выборка мала: 6 из 30»), и прятать её нельзя — по ней принимают решение
    доверять величине или нет.
    """
    foot_html = f'<span class="s-foot">{foot}</span>' if foot else ""
    lab = with_hint(label, hint)
    return (f'<div class="stat {tone}">'
            f'<b class="s-big">{big}</b>'
            f'<span class="s-lab">{lab}</span>'
            f'{foot_html}</div>')


def with_hint(label, hint):
    """Подмешать пояснение в подсказку на подписи величины.

    Если подпись уже несёт подсказку (label собран через tip), пояснение
    дописывается к её тексту — иначе на одном слове оказались бы две разные
    подсказки, и вторая молча победила бы первую. Если подсказки не было,
    пояснение становится ею.
    """
    if not hint:
        return label
    m = re.search(r'data-tip="([^"]*)"', label)
    if m:
        merged = (m.group(1) + " " + hint).strip()
        return label[:m.start(1)] + merged + label[m.end(1):]
    return (f'<span class="tip" tabindex="0" data-tip="{hint}">{label}</span>')


def pos_tone(p):
    v = float(p)
    if v <= 10:
        return "good"
    if v <= 20:
        return "mid"
    return "bad"


def page_str(v):
    """Номер страницы — ОДНОЙ функцией на всю доску, wp.page_of.

    Здесь стояла своя формула int(v // 10) + 1, и на позиции 40,0 она давала
    ПЯТУЮ страницу, тогда как шапка динамики в двадцати сантиметрах ниже
    печатала четвёртую. Сороковой результат — последний на четвёртой странице;
    формула была для нумерации с нуля. Две части доски утверждали разное об
    одном и том же числе.
    """
    p = wp.page_of(v)
    return {1: "первая страница выдачи",
            2: "вторая страница выдачи"}.get(p, f"{p}-я страница выдачи")


def index_block(k, s, per):
    """Индексация: три состояния, а не два.

    «Обошёл и не взял» и «нашёл и не обошёл» — разные диагнозы, и чинятся они
    противоположным: первое означает, что содержание не убедило, второе — что
    до страницы просто не дошли. Раньше на доске было одно число «в индексе» и
    рукописная приписка про очередь, не связанная с ним арифметически: при
    обновлении одного и заморозке другого страница печатала бы часть больше
    целого.
    """
    c = census(k)
    if not c:
        return f"""
      <div class="ibox">
        <div class="ihead"><span>Индексация</span><span>перепись не снята</span></div>
        <p class="ifoot">Поадресная перепись индексации не снята: файл
        <code>data/index_state.csv</code> пуст или недоступен. Это НЕ ноль
        страниц в {tip("индекс")}е — это отсутствие замера, и подставлять сюда
        прежние числа под сегодняшней датой мы не будем.</p>
      </div>"""
    part = round(idx_share(k, s))
    tone = "good" if part >= 90 else ("mid" if part >= 60 else "bad")
    tail = ""
    if c["queued"]:
        tail += (f'<p class="warn-s">Из них <b>{c["queued"]}</b> в состоянии '
                 f'«Google нашёл адрес и не пришёл». Пока страница не в '
                 f'{tip("индекс")}е, улучшать её бессмысленно — показать её '
                 f'некому.</p>')
    if c["crawled_not"]:
        tail += (f'<p class="warn-s">А <b>{c["crawled_not"]}</b> Google обошёл '
                 f'и НЕ взял. Это приговор содержанию, а не очередь: ждать тут '
                 f'нечего, страницы надо менять.</p>')
    top = "".join(f'<li>{_esc(w)} — {n}</li>' for w, n in c["reasons"][:4])
    if top:
        tail += f'<ul class="ireasons">{top}</ul>'
    unseen = c["total"] - c["seen"]
    seen_note = ("" if not unseen else
                 f' Опрошено {c["seen"]} адресов из {c["total"]}; остальные '
                 f'{unseen} — в следующие прогоны.')
    return f"""
      <div class="ibox">
        <div class="ihead">
          <span>Страниц в карте сайта <b>{c["total"]}</b></span>
          <span>В {tip("индекс")}е <b>{c["indexed"]}</b> — это {part}%</span>
        </div>
        <div class="ibar"><span class="{tone}" style="width:{part}%"></span></div>
        <p class="ifoot">Перепись по адресам {d(c["from"])}–{d(c["to"])}.{seen_note}
        Полоса — доля наших страниц, попавших в базу Google, от всех
        опубликованных.</p>
        {tail}
      </div>"""


