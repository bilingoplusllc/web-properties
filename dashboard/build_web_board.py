def weakest(k, s, per):
    """Самое слабое место — словами и СОРАЗМЕРНО баллу: «почти не показывает»
    про сайт на первой странице выдачи было бы неправдой."""
    parts = idx_raw(k, s, per)
    # Неизмеренный признак не может быть «самым слабым»: он никакой.
    known = [(j, v) for j, v in enumerate(parts) if v is not None]
    i, v = min(known, key=lambda p: p[1])
    if i == 0:
        return ("Google знает мало наших страниц" if v < 50
                else "в индексе не все страницы")
    if i == 1:
        return ("Google нас почти не показывает" if v < 30
                else "мы ниже первой тройки" if v < 70
                else "до первого места ещё далеко")
    return ("люди уходят почти сразу" if v < 40
            else "люди задерживаются недостаточно")


