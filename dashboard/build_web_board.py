# Сводный индекс сайта. НЕ отраслевая метрика: наша собственная шкала, и она
# всегда показывается разложенной на составляющие — цифра, происхождение
# которой не видно, на этой доске жить не должна.
# Пять величин, у каждой понятное «сто баллов»:
#   индексация  — все страницы в базе Google;
#   позиция     — первое место в выдаче (30-е и ниже = ноль);
#   CTR         — пять процентов переходов от показов;
#   поведение   — половина визитов не мимолётные;
#   география   — порог премиальной сети пройден.
# ТРИ составляющие равного веса — шаги воронки: Google нас знает, Google нас
# показывает, люди остаются.
#
# Что сюда НЕ входит и почему. Два разных случая, обоим место отметкой рядом:
#   ГЕОГРАФИЯ — это ВОРОТА: проходишь или нет. Оба сайта проходят с запасом,
#   значит компонент никого не различает и просто дарил бы каждому баллы.
#   ОТДАЧА (CTR к ожидаемому на своей позиции) — это ДИАГНОСТИКА, и она
#   улучшается, когда сайту хуже: чем ниже позиция, тем меньше от неё ждут.
#   Стоя в одном среднем с самой позицией, она делала индекс НЕМОНОТОННЫМ —
#   выход с 9,5-го места на 1-е ронял его с 83 до 74, а падение с 30-го на
#   85-е поднимало с 16 до 18. Проверено пересчётом на замороженном CTR.

# Узлы шкалы ПЕРЕХОДОВ, по логарифму: между 0,1 и 1 переходом в сутки разница
# качественная, между 300 и 600 — количественная. Привязка не выдумана: 33
# перехода в сутки — это примерно 1000 сессий в месяц, нижняя ступень
# рекламной лестницы (Journey by Mediavine), а 600 в сутки — уровень, с
# которого начинают разговаривать сети вроде Raptive.
#
# Почему переходы вообще появились в индексе. Их там НЕ БЫЛО НИ В КАКОМ ВИДЕ,
# и вот чего это стоило: с 31.08 по 08.09 MileageCurve заработал ОДИН переход,
# а индекс вырос с 16 до 52 — потому что за те же дни выросла доля индексации.
# Зеркально у GS Pay Tables переходы в сутки упали втрое, а индекс прибавил
# один балл. Индекс, который не двигается вместе с тем, ради чего сайт
# существует, — это не подсказка, а украшение.
CLICK_POINTS = [(0.1, 0), (1, 25), (10, 50), (33, 67), (600, 100)]


def click_score(per_day):
    """Переходы в сутки в баллы, по логарифмической шкале."""
    if per_day <= 0.1:
        return 0.0
    if per_day >= 600:
        return 100.0
    lg = math.log10(per_day)
    for (x1, y1), (x2, y2) in zip(CLICK_POINTS, CLICK_POINTS[1:]):
        if x1 <= per_day <= x2:
            a1, a2 = math.log10(x1), math.log10(x2)
            return y1 + (lg - a1) / (a2 - a1) * (y2 - y1)
    return 0.0


# Узлы кривой видимости. Кликабельность падает не по прямой: между первым и
# третьим местом разница огромная, между двадцать пятым и тридцатым — никакой.
VIS_POINTS = [(1, 100), (3, 80), (10, 50), (20, 20), (30, 0)]


def vis_score(pos):
    """Плато 1–3 убрано НАРОЧНО: пока третье место равнялось первому,
    видимость переставала расти у вершины, и вклад позиции там держала одна
    только отдача — со знаком минус. Отсюда и брался провал индекса при
    выходе в топ. Пол опущен до нуля: комментарий обещал «30-е и ниже = ноль»,
    а функция возвращала пять — код противоречил сам себе в соседних строках."""
    if pos <= 1:
        return 100.0
    if pos >= 30:
        return 0.0
    for (x1, y1), (x2, y2) in zip(VIS_POINTS, VIS_POINTS[1:]):
        if x1 <= pos <= x2:
            return y1 + (pos - x1) / (x2 - x1) * (y2 - y1)
    return 5.0

