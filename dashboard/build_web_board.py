# 13. КОНТРАСТ ОТМЕТОК ГРАФИКА. Столбцы цвета --brand-soft на фоне --sunken
#     давали 1,03:1 — их не было видно вовсе, и владелец написал «ничего не
#     видно». Тот же класс уже стоил нам карточки при 1,07:1. Порог 3:1 — это
#     минимум WCAG для НЕтекстовых графических объектов.


def _lum(h):
    h = h.lstrip("#")
    ch = [int(h[i:i + 2], 16) / 255 for i in (0, 2, 4)]
    ch = [(x / 12.92 if x <= 0.03928 else ((x + 0.055) / 1.055) ** 2.4)
          for x in ch]
    return 0.2126 * ch[0] + 0.7152 * ch[1] + 0.0722 * ch[2]


def _contrast(a, b):
    la, lb = _lum(a), _lum(b)
    hi, lo = max(la, lb), min(la, lb)
    return (hi + 0.05) / (lo + 0.05)


_VARS = dict(re.findall(r"(--[a-z0-9-]+):\s*(#[0-9A-Fa-f]{6})", HTML))
# Отметка -> фон, на котором она реально лежит.
#     Подложка --chart-window сюда НЕ входит: это фон, а не
#     отметка, и требовать от фона 3:1 значит сделать его непригодным как фон.
_MARKS = [("--chart-bar", "--surface"), ("--chart-line", "--surface")]
_low = []
for _mk, _bg in _MARKS:
    if _mk in _VARS and _bg in _VARS:
        _c = _contrast(_VARS[_mk], _VARS[_bg])
        if _c < 3.0:
            _low.append("%s на %s = %.2f:1" % (_mk, _bg, _c))
_g.append(_gate("отметки графиков контрастны (>=3:1)", not _low, str(_low)))

# 12. Неизмеренный признак не может быть уверенным числом в соседнем квадрате.
#     Индекс помечал вовлечённость MileageCurve как «н/д» по шести визитам, а
#     квадрат двадцатью сантиметрами ниже показывал «50,0%» зелёным.
