def period_inputs(k):
    """Кнопки окон. У каждой — вопрос, на который окно отвечает, и пометка,
    если сайт этого окна ещё не прожил."""
    out = []
    for p, name, question in PERIODS:
        m = mm(k, p)
        ok = m.get("available", True)
        chk = " checked" if p == DEFAULT_PERIOD else ""
        cls = "" if ok else ' class="off"'
