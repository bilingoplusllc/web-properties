def stat(big, label, hint, tone="", foot=""):
    """Квадрат с одной крупной величиной.

    hint — ПОЯСНЕНИЕ, и оно уходит под наведение на подпись, а не занимает
    строку под ней. Четыре квадрата в ряд давали четыре строки пояснений и
    съедали то место, ради которого квадрат и сделан: крупное число, видное
    сразу.

    foot остаётся видимым: это не пояснение, а оговорка о годности числа
    («выборка мала: 6 из 30»), и прятать её нельзя — по ней принимают решение
    доверять величине или нет.
    """
    foot_html = f'<span class="s-foot">{foot}</span>' if foot else ""
    lab = with_hint(label, hint)
    return (f'<div class="stat {tone}">'
            f'<b class="s-big">{big}</b>'
            f'<span class="s-lab">{lab}</span>'
            f'{foot_html}</div>')


def with_hint(label, hint):
    """Подмешать пояснение в подсказку на подписи величины.

    Если подпись уже несёт подсказку (label собран через tip), пояснение
    дописывается к её тексту — иначе на одном слове оказались бы две разные
    подсказки, и вторая молча победила бы первую. Если подсказки не было,
    пояснение становится ею.
    """
    if not hint:
        return label
    m = re.search(r'data-tip="([^"]*)"', label)
    if m:
        merged = (m.group(1) + " " + hint).strip()
        return label[:m.start(1)] + merged + label[m.end(1):]
    return (f'<span class="tip" tabindex="0" data-tip="{hint}">{label}</span>')


