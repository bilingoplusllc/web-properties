def expected_ctr(pos):
    """Сколько переходов обычно даёт ЭТА позиция. Отраслевая кривая
    0.28 * позиция^-0.7; нужна, чтобы отделить «нас не выбирают» от
    «мы просто стоим низко». Без неё CTR был бы дублем позиции."""
    return 0.28 * pos ** -0.7 * 100


# Ниже этого числа визитов доля не считается. Интервал на 50% при шести
# наблюдениях — примерно от 12% до 88%: по такому «признаку» нельзя не то что
# ставить балл, а даже сказать, в какую он сторону.
MIN_SESSIONS = 30


def idx_raw(k, s, per):
    """Сырые величины. Усредняются ОНИ, а округление одно и в самом конце:
    округлять части, а потом их среднее — значит заряжать люфт до половины
    балла на каждой.

    None означает НЕ ИЗМЕРЕНО, и это не ноль: ноль — это «плохо», а None —
    «нечем судить». Разница видна на MileageCurve, где три вовлечённых визита
    из шести давали ровно планку и ровно сто баллов.
    """
    m = mm(k, per)
    return [
        click_score(m["clicks_day"]),
        vis_score(float(m["position"])),
    ]


def idx_parts(k, s, per):
    return [None if v is None else round(v) for v in idx_raw(k, s, per)]


def idx_measured(k, s, per):
    """Сколько признаков реально измерено — ПЕЧАТАЕТСЯ рядом с баллом.

    Раньше эта функция существовала и не вызывалась ни разу. Из-за этого
    рядом стояли 52 и 82, посчитанные по РАЗНОМУ числу слагаемых: у одного
    сайта два, у другого три, и на общих двух было бы 52 против 73. Число,
    которое нельзя сравнить, обязано об этом сказать само.
    """
    return sum(1 for v in idx_raw(k, s, per) if v is not None)


def idx_gates(k, s, per):
    """ВОРОТА: признаки, которые баллов НЕ ДАЮТ, но могут понизить.

    Почему они не слагаемые. Доля индексации у обоих сайтов теперь 93% и 99%:
    она перестала различать сайты и при этом давала MileageCurve 90% его
    балла — сайт с одним переходом за неделю получал 52 из-за того, что
    Google завёл его файлы. Вовлечённость — такая же пройденная планка:
    60,5% при планке 50% дают 121%, обрезаемые до 100, то есть максимум
    просто за то, что порог перейдён.

    Ворота работают потолком: индекс не может быть выше доли страниц в
    индексе. Сайт, половины которого нет в поиске, не бывает хорошим, но и
    сайт, весь попавший в индекс, от этого хорошим не становится.
    """
    m = mm(k, per)
    share = idx_share(k, s)
    eng = float(m["engagement"].replace("%", "").replace(",", "."))
    out = []
    if share is None:
        out.append(("индексация", None, "перепись не снята"))
    else:
        out.append(("индексация", share, "%d%% страниц в индексе" % round(share)))
    if m["sessions"] >= MIN_SESSIONS:
        out.append(("вовлечённость", eng,
                    "%s визитов не мимолётные" % m["engagement"]))
    else:
        out.append(("вовлечённость", None,
                    "визитов %d, нужно %d" % (m["sessions"], MIN_SESSIONS)))
    return out


def idx_ceiling(k, s, per):
    """Потолок из ворот. None — ворота не измерены, потолка нет."""
    share = idx_share(k, s)
    return None if share is None else share


def payoff(k, per):
    """Отдача — ОТМЕТКА, не слагаемое. Без обрезки: перевыполнение здесь
    как раз и есть то, что надо увидеть."""
    m = mm(k, per)
    pos = float(m["position"])
    ctr = float(m["ctr"].replace("%", "").replace(",", "."))
    exp = expected_ctr(pos)
    r = ctr / exp
    if r >= 1:
        word = f"в {num_ru(r)} раза лучше своего места"  # 1,2 / 1,5 — всегда «раза»
        tone = "good"
    else:
        k_ = round(1 / r)
        word = ("в " + plural(k_, "раз", "раза", "раз")
                + " хуже своего места")
        tone = "bad"
    # На виду — вывод. Всё «почему» уходит под наведение: под индексом
    # успела вырасти стена, где объяснение было длиннее самих данных.
    why = (f'Наш CTR {m["ctr"]} против {num_ru(exp)}%, которые обычно даёт '
           f'позиция {num_ru(pos)}. В среднее НЕ входит: это диагностика, а '
           f'не качество — чем ниже место, тем меньше от него ждут, и '
           f'величина улучшается, когда сайту хуже. Стоя в одном среднем с '
           f'самой позицией, она делала индекс немонотонным: выход на первое '
           f'место ронял его на девять баллов. Кривая ожидаемого — '
           f'приближение по публичным сводкам, мы её не перепроверяли; на '
           f'баллы не влияет.')
    return tone, word, why, r * 100


def num_ru(x, digits=1):
    return ("%.*f" % (digits, x)).replace(".", ",")


def idx_why(k, s, per):
    """Откуда взялся каждый балл. Обоснование обязано ДОВОДИТЬ до балла:
    владелец справедливо спросил, почему «7% при ожидаемых 5,8%» это сто —
    ответ (121% и обрезка) был в формуле, но не на экране."""
    m = mm(k, per)
    pos = float(m["position"])
    cl_t = (f'{m["clicks"]} за {m["win_s"]} · '
            f'{num_ru(m["clicks_day"], 2)} в сутки')
    lo = hi = None
    for (x1, y1), (x2, y2) in zip(VIS_POINTS, VIS_POINTS[1:]):
        if x1 <= pos <= x2:
            lo, hi = (x1, y1), (x2, y2)
            break
    if lo:
        vis_t = (f'позиция {num_ru(pos)} · между {lo[0]}-м ({lo[1]}) '
                 f'и {hi[0]}-м ({hi[1]})')
    else:
        vis_t = f'позиция {num_ru(pos)} · ниже 30-го места'
    return [cl_t, vis_t]


def idx_compose(parts, ceiling):
    """Сборка балла из признаков и потолка. ЧИСТАЯ функция.

    Вынесена отдельно нарочно: пока сборка сидела внутри idx_score, проверить
    её можно было только на живых данных — а на живых данных потолок сегодня
    не срабатывает ни у одного сайта, и охраняющий его гейт покраснеть не мог.
    Чистую функцию проверяют известными ответами.
    """
    r = [v for v in parts if v is not None]
    if not r:
        return 0
    v = sum(r) / len(r)
    if ceiling is not None:
        v = min(v, ceiling)
    return round(v)


def idx_score(k, s, per):
    """Среднее по ИЗМЕРЕННЫМ признакам, не выше потолка из ворот.

    Неизмеренный признак не входит ни как ноль, ни как сто — он не входит
    никак, а его отсутствие подписано рядом.
    """
    return idx_compose(idx_raw(k, s, per), idx_ceiling(k, s, per))


