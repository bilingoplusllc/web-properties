    _want = set(re.findall("hub[.]html#([a-z0-9-]+)", HTML))
    _dead = sorted(_want - _ids)
    _g.append(_gate("ссылки в документацию ведут в существующие главы",
                    not _dead, str(_dead)))
    #     И сама ссылка на документацию обязана быть. Проверка «якоря ведут
    #     в существующие главы» стала ХОЛОСТОЙ, когда при чистке доски убрали
    #     глубокие ссылки: якорей ноль, множество пустое, гейт вечно зелёный.
    #     Проверка, которая не может покраснеть, ничего не охраняет.
    _g.append(_gate("на документацию есть ссылка с доски",
                    'href="hub.html' in HTML,
                    "хаб недостижим с доски"))

