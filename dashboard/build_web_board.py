def ru_time(x):
    """GA4 отдаёт «1m 43s» и «14s». На русской доске это читается как
    недопереведённый интерфейс, а не как величина."""
    m = re.match(r"(?:([0-9]+)m )?([0-9]+)s", x.strip())
    if not m:
        return x
    mins, secs = m.group(1), int(m.group(2))
    if mins:
        return "%s мин %02d с" % (mins, secs)
    return "%d сек" % secs


def compare_rows():
    def val(x):
        m = re.findall(r"\d+(?:[.,]\d+)?", x.replace(" ", ""))
        return float(m[0].replace(",", ".")) if m else None

    out = []
    for label, fn, better in COMPARE:
        cells = [fn(s["key"], s) for s in SITES]
        best = -1
        if better:
            nums = [val(c) for c in cells]
            if all(n is not None for n in nums) and nums[0] != nums[1]:
                best = nums.index(min(nums) if better == "min" else max(nums))
        tds = "".join(f'<td class="num{" win" if i == best else ""}">{c}</td>'
                      for i, c in enumerate(cells))
        out.append(f"<tr><th>{label}</th>{tds}</tr>")
    return "".join(out)



