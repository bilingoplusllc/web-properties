def _fmt_pct(x):
    return ("%.1f" % x).replace(".", ",") + "%"


def census(k):
    """Перепись индексации сайта или None, если она не снята.

    Раньше эти числа были ЕДИНСТВЕННЫМИ на доске, которые не приходили ниоткуда:
    рукописный словарь с датами 21.08 и 26.08, тогда как плашка в шапке той же
    страницы объявляла все числа снятыми ботом сегодня. Теперь их снимает
    поадресная перепись, а её отсутствие — НАЗВАННОЕ состояние, а не ноль и не
    вчерашнее число под сегодняшней датой.
    """
    return (wp.INDEX or {}).get(k)


def pages_of(k, s):
    """Сколько у сайта страниц. Источник — КАРТА САЙТА, а не литерал.

    Число было вбито руками в SITES и жило ещё в трёх местах: в колонке
    pages_built снимка GA4, в реестре и в мёртвом генераторе. Ни одна пара не
    сверялась, и 09.09 они разошлись: сборка подтянула свежие данные NHTSA,
    часть поколений не прошла порог отчётов, и сайт стал 307 страниц вместо
    353. Литерал остался прежним и был бы знаменателем доли индексации.

    Литерал сохранён ТОЛЬКО как запасной вариант на случай, когда переписи
    нет, и в этом случае он назван запасным на самой странице.
    """
    c = census(k)
    return c["total"] if c else s["pages"]


def idx_share(k, s):
    """Доля страниц в индексе, 0..100, или None — «перепись не снята».

    Числитель и знаменатель берутся из ОДНОЙ переписи, поэтому доля больше ста
    невозможна по построению и обрезки здесь нет. Она была бы нужна в прежней
    сборке, где «в индексе» пришло бы из API, а число страниц стояло бы
    рукописным: расхождение на один адрес давало бы полосу шириной 101%.
    Знаменатель охраняется гейтом «карта сайта против объявленного числа».
    """
    c = census(k)
    if not c or not c["total"] or not c["seen"]:
        return None
    return c["indexed"] / c["total"] * 100


