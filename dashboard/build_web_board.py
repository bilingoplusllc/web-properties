def beh_tone(m):
    """Цвет поведенческого квадрата — по ЧИСЛУ, а не по имени сайта.

    Стояло `"good" if k == "gspaytables" else "bad"`: один сайт был бы зелёным
    при любых цифрах, другой красным при любых. Правило, зашитое под сайт,
    перестаёт быть измерением. И если выборки нет, цвета тоже нет: серый —
    это «нечем судить», а не «средне».
    """
    if m["sessions"] < MIN_SESSIONS:
        return ""
    eng = float(m["engagement"].replace("%", "").replace(",", "."))
    return "good" if eng >= 50 else ("mid" if eng >= 25 else "bad")


def beh_foot(m):
    """Подпись под квадратом. Если выборки мало — так и написано, иначе
    квадрат уверенно показывает долю, которую индекс рядом помечает «н/д»."""
    if m["sessions"] < MIN_SESSIONS:
        return f'выборка мала: {m["sessions"]} из {MIN_SESSIONS}'
    return m["win_g"]


def ctr_stat(m):
    """CTR при четырёх переходах — такая же ловушка, как доля по шести визитам.

    Доля от крошечного числителя выглядит точной величиной («0,7%»), а меняется
    целыми скачками: один переход туда-сюда двигает её на четверть. Порог тот
    же, что и у поведения, и берётся из той же константы — сравнений с
    литералом 30 в коде быть не должно нигде.
    """
    small = m["clicks"] < MIN_SESSIONS
    hint = ""
    if small:
        hint = (f'Переходов за это окно всего {m["clicks"]}: один туда-сюда '
                f'двигает долю на четверть, поэтому цвета у неё нет.')
    tone = "" if small else (
        "good" if float(m["ctr"].replace("%", "").replace(",", ".")) >= 2
        else "bad")
    foot = f'выборка мала: {m["clicks"]} из {MIN_SESSIONS}' if small else ""
    return stat(m["ctr"], tip("CTR"), hint, tone, foot)


